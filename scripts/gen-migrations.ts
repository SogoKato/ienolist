// Bundles the SQL migrations into the Worker, which cannot read drizzle/ at run time. Run: pnpm gen
import { writeFileSync } from "node:fs";
import { readMigrations } from "../src/db/sqlite.ts";

const migrations = readMigrations();
writeFileSync(
  new URL("../src/db/migrations.generated.ts", import.meta.url),
  `// GENERATED by scripts/gen-migrations.ts (pnpm gen) - do not edit\nexport const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 1)};\n`,
);
console.log(`migrations: ${migrations.length}`);
