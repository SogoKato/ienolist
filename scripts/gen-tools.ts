// Serializes the tools/list payload at build time. Converting the zod schemas
// at runtime cost 3-10 ms CPU on the first call in each isolate, which is most
// of the 10 ms budget on Cloudflare Workers Free. Run: pnpm gen
import { writeFileSync } from "node:fs";
import { serializeTools } from "../src/mcp/registry.ts";
import { tools } from "../src/mcp/tools.ts";

const json = serializeTools(tools as never);
writeFileSync(
  new URL("../src/mcp/tools.generated.ts", import.meta.url),
  `// GENERATED by scripts/gen-tools.ts (pnpm gen) - do not edit\nexport const TOOLS_JSON = ${JSON.stringify(json)};\n`,
);
console.log(`tools/list: ${tools.length} tools, ${json.length} bytes`);
